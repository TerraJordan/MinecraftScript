"""
picker.py — вспомогательный скрипт для калибровки координат кликов.

Запусти его, наведи курсор на нужный элемент интерфейса в окне Minecraft
и посмотри координаты в консоли. Для остановки нажми Ctrl+C.

ВАЖНО: координаты, которые выводит этот скрипт, — АБСОЛЮТНЫЕ (относительно
всего экрана). Прежде чем вписать их в CLICKS_SEQUENCE в bot.py, нужно
вычесть координаты левого верхнего угла окна Minecraft (win_x, win_y),
которые bot.py печатает при запуске (см. "Окно найдено в координатах").

Пример:
    Абсолютные координаты клика: (930, 560)
    Окно Minecraft начинается в: (700, 200)
    Относительные координаты для CLICKS_SEQUENCE: (930 - 700, 560 - 200) = (230, 360)
"""

import time
import pyautogui

print("Перемещайте мышь для определения координат. Для выхода нажмите Ctrl+C.")

try:
    while True:
        x, y = pyautogui.position()
        print(f"Координаты мыши (абсолютные): X={x}, Y={y}", end="\r")
        time.sleep(0.1)
except KeyboardInterrupt:
    print("\nСбор координат завершён.")
