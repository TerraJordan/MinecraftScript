"""
recorder.py — ручной захват шагов сценария по явному действию пользователя.

ВАЖНО: этот модуль НЕ является фоновым перехватчиком (кейлоггером). Он не
слушает клавиатуру/мышь постоянно и не различает, куда направлен фокус
системы. Вместо этого пользователь сам, явно, через кнопки в GUI отмечает
каждый шаг, который нужно записать:

  - "Отметить удержание клавиши" — пользователь вводит, какую клавишу он
    только что удерживал в игре, и на сколько миллисекунд (или таймер
    "начать/закончить удержание", который просто меряет время между двумя
    явными нажатиями кнопок в самом GUI).
  - "Отметить клик" — пользователь наводит курсор в окно Minecraft, затем
    нажимает кнопку в GUI, и recorder.py считывает ТЕКУЩУЮ позицию курсора
    в момент явного нажатия кнопки (одномоментный снимок, а не слежка).

Таким образом, запись работает только тогда, когда пользователь сам решает
зафиксировать шаг, и никогда не работает в фоне и не собирает произвольный
ввод (пароли, переписку и т.д.).

Формат записанных шагов идентичен тому, что использует bot.py:
  {"type": "key_hold", "key": "w", "duration_ms": 850}
  {"type": "mouse_click", "x": 230, "y": 360}
"""

import time


class ManualRecorder:
    """
    Хранит список шагов, накопленных за время сессии записи.
    Все методы вызываются только в ответ на явное действие пользователя
    в GUI (нажатие кнопки) — recorder ничего не делает сам по себе.
    """

    def __init__(self):
        self.steps = []
        self._hold_start_time = None
        self._hold_key = None

    def start_key_hold(self, key_name: str):
        """
        Вызывается по нажатию кнопки "Начать удержание" в GUI.
        Запоминает момент начала и клавишу — таймер работает только
        внутри самого приложения, не перехватывая реальную клавиатуру.
        """
        self._hold_key = key_name.strip().lower()
        self._hold_start_time = time.monotonic()

    def finish_key_hold(self):
        """
        Вызывается по нажатию кнопки "Закончить удержание".
        Вычисляет длительность в мс и добавляет шаг key_hold в список.
        Возвращает добавленный шаг (для отображения в GUI) или None,
        если start_key_hold не вызывался.
        """
        if self._hold_start_time is None or self._hold_key is None:
            return None

        duration_ms = int((time.monotonic() - self._hold_start_time) * 1000)
        duration_ms = max(duration_ms, 1)  # защита от нулевой/отрицательной длительности

        step = {"type": "key_hold", "key": self._hold_key, "duration_ms": duration_ms}
        self.steps.append(step)

        self._hold_start_time = None
        self._hold_key = None
        return step

    def capture_click(self, x: int, y: int):
        """
        Вызывается по нажатию кнопки "Отметить клик здесь".
        x, y — координаты, переданные GUI (снимок позиции курсора в момент
        нажатия кнопки, снятый самим GUI-фреймворком, а не фоновым хуком).
        Ожидаются координаты уже ОТНОСИТЕЛЬНО окна Minecraft — GUI должен
        пересчитать их из абсолютных перед вызовом этого метода.
        """
        step = {"type": "mouse_click", "x": int(x), "y": int(y)}
        self.steps.append(step)
        return step

    def clear(self):
        """Очищает список записанных шагов (кнопка "Очистить запись" в GUI)."""
        self.steps = []
        self._hold_start_time = None
        self._hold_key = None

    def get_steps(self):
        """Возвращает копию списка записанных шагов."""
        return list(self.steps)
